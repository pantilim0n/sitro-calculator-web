const MAX_API_HOST = 'platform-api2.max.ru';

export function maxApiRequest(path, {token, method = 'GET', body} = {}) {
  if (!token) throw new Error('Не указан токен MAX');
  if (typeof path !== 'string' || !path.startsWith('/')) throw new Error('Некорректный путь MAX API');
  const payload = body === undefined ? null : JSON.stringify(body);
  return new Promise((resolve, reject) => {
    const request = https.request({
      protocol: 'https:',
      hostname: MAX_API_HOST,
      port: 443,
      path,
      method,
      ca: RUSSIAN_TRUSTED_ROOT_CA,
      servername: MAX_API_HOST,
      headers: {
        Authorization: token,
        Accept: 'application/json',
        ...(payload ? {'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload)} : {})
      },
      timeout: 15000
    }, response => {
      let raw = '';
      response.setEncoding('utf8');
      response.on('data', chunk => {
        raw += chunk;
        if (raw.length > 2_000_000) request.destroy(new Error('Слишком большой ответ MAX'));
      });
      response.on('end', () => {
        let data = {};
        try { data = raw ? JSON.parse(raw) : {}; } catch {}
        resolve({ok: response.statusCode >= 200 && response.statusCode < 300, status: response.statusCode || 0, data});
      });
    });
    request.on('timeout', () => request.destroy(new Error('MAX не ответил вовремя')));
    request.on('error', reject);
    if (payload) request.write(payload);
    request.end();
  });
}
